import { promises as fs } from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'

export const EXCLUDE_BEGIN = '# >>> skill-store (managed) >>>'
export const EXCLUDE_END = '# <<< skill-store (managed) <<<'

export interface GitExcludeResult {
  file: string
  /** Entries written to the managed block (posix paths relative to the repo root). */
  entries: string[]
  changed: boolean
  /** Paths that could not be represented (outside the repository). */
  skipped: string[]
}

function git(cwd: string, args: string[]): string | null {
  const result = spawnSync('git', ['-C', cwd, ...args], {
    encoding: 'utf8',
    stdio: 'pipe',
  })
  if (result.error || result.status !== 0) return null
  return result.stdout.trim()
}

/**
 * Resolve the repository root and the correct `info/exclude` path for it,
 * including linked worktrees (`git rev-parse --git-path`).
 */
export async function resolveGitExcludeFile(
  projectRoot: string,
): Promise<{ topLevel: string; excludeFile: string } | null> {
  const topLevel = git(projectRoot, ['rev-parse', '--show-toplevel'])
  if (!topLevel) return null

  const gitPath = git(topLevel, ['rev-parse', '--git-path', 'info/exclude'])
  if (!gitPath) return null

  return {
    topLevel,
    excludeFile: path.resolve(topLevel, gitPath),
  }
}

export function stripManagedBlock(content: string): string {
  const lines = content.split(/\r?\n/)
  const kept: string[] = []
  let inside = false

  for (const line of lines) {
    if (line.trim() === EXCLUDE_BEGIN) {
      inside = true
      continue
    }
    if (line.trim() === EXCLUDE_END) {
      inside = false
      continue
    }
    if (!inside) kept.push(line)
  }

  return kept.join('\n').replace(/\s+$/, '')
}

export function renderManagedBlock(entries: string[]): string {
  const sorted = [...new Set(entries)].sort((a, b) => a.localeCompare(b))
  return [
    EXCLUDE_BEGIN,
    '# Generated by `skill-store sync`. Do not edit this block manually.',
    ...sorted,
    EXCLUDE_END,
  ].join('\n')
}

export function parseManagedBlock(content: string): string[] {
  const lines = content.split(/\r?\n/)
  const entries: string[] = []
  let inside = false

  for (const line of lines) {
    if (line.trim() === EXCLUDE_BEGIN) {
      inside = true
      continue
    }
    if (line.trim() === EXCLUDE_END) break
    if (inside) {
      const value = line.trim()
      if (value !== '' && !value.startsWith('#')) entries.push(value)
    }
  }

  return entries
}

function toPosixRelative(from: string, to: string): string | null {
  const relative = path.relative(from, to)
  if (relative === '' || relative.startsWith('..') || path.isAbsolute(relative)) return null
  return relative.split(path.sep).join('/')
}

/**
 * Read the managed block currently present in the repository's exclude file.
 */
export async function readGitExclude(
  projectRoot: string,
): Promise<{ file: string; entries: string[] } | null> {
  const resolved = await resolveGitExcludeFile(projectRoot)
  if (!resolved) return null

  let content: string
  try {
    content = await fs.readFile(resolved.excludeFile, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      return { file: resolved.excludeFile, entries: [] }
    }
    throw error
  }

  return { file: resolved.excludeFile, entries: parseManagedBlock(content) }
}

/**
 * Write the Skill Store-managed block of `<repo>/.git/info/exclude`.
 *
 * Only the managed block is touched: user content is preserved verbatim and the
 * shared `.gitignore` is never modified.
 */
export async function updateGitExclude(
  projectRoot: string,
  absolutePaths: string[],
): Promise<GitExcludeResult | null> {
  const resolved = await resolveGitExcludeFile(projectRoot)
  if (!resolved) return null

  const entries: string[] = []
  const skipped: string[] = []
  for (const absolutePath of absolutePaths) {
    const relative = toPosixRelative(resolved.topLevel, absolutePath)
    if (relative) entries.push(relative)
    else skipped.push(absolutePath)
  }

  let original = ''
  try {
    original = await fs.readFile(resolved.excludeFile, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error
  }

  const base = stripManagedBlock(original)
  const block = entries.length > 0 ? renderManagedBlock(entries) : ''
  const next = block ? `${base === '' ? '' : `${base}\n\n`}${block}\n` : base === '' ? '' : `${base}\n`

  if (next === original) {
    return { file: resolved.excludeFile, entries, changed: false, skipped }
  }

  await fs.mkdir(path.dirname(resolved.excludeFile), { recursive: true })
  await fs.writeFile(resolved.excludeFile, next, 'utf8')
  return { file: resolved.excludeFile, entries, changed: true, skipped }
}
